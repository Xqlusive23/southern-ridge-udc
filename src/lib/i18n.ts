export function isLocale(value: string | null | undefined): value is AppLocale {
  return LOCALES.includes((value ?? "") as AppLocale);
}

export function isCurrency(value: string | null | undefined): value is AppCurrency {
  return CURRENCIES.includes((value ?? "") as AppCurrency);
}

export function normalizeLocale(value: string | null | undefined): AppLocale {
  return isLocale(value) ? value : "en";
}

export function normalizeCurrency(value: string | null | undefined): AppCurrency {
  return isCurrency(value) ? value : "USD";
}

export function t(locale: string | null | undefined, key: string) {
  const lang = normalizeLocale(locale);
  return MESSAGES[lang][key] ?? MESSAGES.en[key] ?? key;
}
